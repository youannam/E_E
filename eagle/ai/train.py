"""
Train and evaluate the Isolation Forest model.

Usage (from the project root):
    python -m ai.train                 # generate data, train, evaluate, save to MODEL_DIR
    python -m ai.train --seed 7 --model-dir ai/models

Steps:
  1. Generate the synthetic dataset (ai/dataset.py) and save it to data/generated/.
  2. Turn raw events into one feature row per user-day (ai/features.py).
  3. Time-aware split: train ONLY on the earlier, normal-only period; evaluate on the
     later period that also contains injected scenario days. The model never sees the
     test days during training, so the evaluation is not done on training data.
  4. Train, learn the score calibration, evaluate, save model + metadata.
"""

import argparse
import json
import logging
import os
from datetime import datetime, timezone
from pathlib import Path

from dotenv import load_dotenv

from ai import dataset
from ai.evaluate import classification_metrics, detection_rate_by_scenario, score_distribution
from ai.features import FEATURE_NAMES, FEATURE_SCHEMA_VERSION, build_feature_table
from ai.model import normalize_score, new_version_name, raw_scores, save_model, train_model

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data" / "generated"


def prepare_data(seed: int):
    events, labels = dataset.generate_dataset(seed)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    events.to_csv(DATA_DIR / "training_events.csv", index=False)
    labels.to_csv(DATA_DIR / "training_labels.csv", index=False)

    features = build_feature_table(events)
    table = features.merge(labels, on=["user_id", "day"], how="inner")
    return events, table


def run_training(seed: int, model_dir: Path, data_seed: int = dataset.DEFAULT_SEED) -> dict:
    events, table = prepare_data(data_seed)
    train_table = table[table["period"] == "train"]
    test_table = table[table["period"] == "test"].copy()

    model, calibration = train_model(train_table, seed=seed)

    test_raw = raw_scores(model, test_table)
    test_table["anomaly_score"] = [normalize_score(value, calibration) for value in test_raw]
    test_table["predicted"] = (test_raw > calibration["threshold_raw_score"]).astype(int)
    train_scores = [normalize_score(value, calibration) for value in raw_scores(model, train_table)]

    metrics = {
        "evaluation_note": ("Measured on SYNTHETIC data from this project's simulator (time-aware split). "
                            "These numbers show the pipeline works on the simulated scenarios; they are "
                            "not evidence of real-world detection performance."),
        "test_period_ai_only": classification_metrics(test_table["label"], test_table["predicted"]),
        "detection_rate_by_scenario": detection_rate_by_scenario(test_table),
        "training_score_distribution": score_distribution(train_scores),
        "test_score_distribution": score_distribution(test_table["anomaly_score"]),
    }

    metadata = {
        "version": new_version_name(),
        "algorithm": "IsolationForest (scikit-learn), 200 trees, raw daily counts",
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "random_seed": seed,
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "feature_names": FEATURE_NAMES,
        "aggregation_window": "1 day per user (local organization time)",
        "training_dataset": {
            "reference": "data/generated/training_events.csv (synthetic, generated by ai/dataset.py)",
            "data_seed": data_seed,
            "raw_events": int(len(events)),
            "train_user_days": int(len(train_table)),
            "test_user_days": int(len(test_table)),
            "train_period": f"{train_table['day'].min()} to {train_table['day'].max()}",
            "test_period": f"{test_table['day'].min()} to {test_table['day'].max()}",
        },
        "calibration": calibration,
        "metrics": metrics,
    }
    save_model(model, metadata, model_dir)
    (DATA_DIR / "last_evaluation.json").write_text(json.dumps(metrics, indent=2))
    return metadata


def main():
    load_dotenv()
    parser = argparse.ArgumentParser(description="Train the Eagle Eye Isolation Forest model")
    parser.add_argument("--seed", type=int, default=42, help="random seed for the model")
    parser.add_argument("--data-seed", type=int, default=dataset.DEFAULT_SEED, help="random seed for the synthetic data")
    parser.add_argument("--model-dir", default=os.getenv("MODEL_DIR", "ai/models"))
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    print("Generating synthetic data and training the model (this takes under a minute)...")
    metadata = run_training(args.seed, Path(args.model_dir), args.data_seed)
    ai_metrics = metadata["metrics"]["test_period_ai_only"]
    print(f"Saved model {metadata['version']} to {args.model_dir}")
    print(f"Training user-days: {metadata['training_dataset']['train_user_days']}, "
          f"test user-days: {metadata['training_dataset']['test_user_days']}")
    print("AI-only results on the synthetic test period:")
    print(f"  precision={ai_metrics['precision']}  recall={ai_metrics['recall']}  "
          f"f1={ai_metrics['f1_score']}  false_positive_rate={ai_metrics['false_positive_rate']}")
    print(f"  confusion matrix: {ai_metrics['confusion_matrix']}")
    print("Detection rate per scenario:")
    for scenario, values in metadata["metrics"]["detection_rate_by_scenario"].items():
        print(f"  {scenario:20s} {values['flagged']}/{values['days']}")


if __name__ == "__main__":
    main()
