// Small labels used in tables and headers.
import type { AlertStatus, RiskLevel } from "../api/types";
import { formatScore, humanize } from "../utils/format";

export function RiskBadge({ level, score }: { level: RiskLevel; score?: number }) {
  return (
    <span className={`risk-badge risk-${level.toLowerCase()}`}>
      {score !== undefined && <strong>{formatScore(score)}</strong>}
      {humanize(level)}
    </span>
  );
}

export function StatusBadge({ status }: { status: AlertStatus | string }) {
  return <span className={`status-badge status-${status.toLowerCase()}`}>{humanize(status)}</span>;
}

export function SeverityText({ severity }: { severity: string }) {
  return <span className={`severity severity-${severity.toLowerCase()}`}>{humanize(severity)}</span>;
}

/** Marks data that came from the simulator, so nobody mistakes it for real monitoring data. */
export function SimulatedTag() {
  return (
    <span className="simulated-tag" title="Generated by the Eagle Eye simulator (synthetic data)">
      Simulated
    </span>
  );
}

export function SensitivityText({ value }: { value: string | null }) {
  if (!value) return <span className="muted">—</span>;
  return <span className={`sensitivity sensitivity-${value.toLowerCase()}`}>{humanize(value)}</span>;
}
